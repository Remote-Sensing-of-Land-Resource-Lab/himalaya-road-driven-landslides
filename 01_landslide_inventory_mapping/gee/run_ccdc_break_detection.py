def buildCoefsRMSEMagnitude(fit, nSegments, targetBand):
  # Build coefficient, RMSE, and magnitude images from the CCDC result
    segmentTag = [f"S{i}" for i in range(1, nSegments + 1)]
    zeros = ee.Image(ee.Array(ee.List.repeat(0, nSegments)))

    # Build the magnitude image
    magImg = fit.select(targetBand + '_magnitude').arrayCat(zeros, 0).float().arraySlice(0, 0, nSegments)
    magImages = magImg.arrayFlatten([ee.List([tag + '_' + targetBand + '_MAG' for tag in segmentTag])])
    zeros = ee.Image(ee.Array(ee.List.repeat(0, nSegments)))
    # Build the RMSE image
    rmseImg = fit.select(targetBand + '_rmse').arrayCat(zeros, 0).float().arraySlice(0, 0, nSegments)
    rmseImages = rmseImg.arrayFlatten([ee.List([tag + '_' + targetBand + '_RMSE' for tag in segmentTag])])
    # Build the coefficient image
    bandTag = targetBand + '_coefs'
    harmonicTag = ['INTP','SLP','COS','SIN','COS2','SIN2','COS3','SIN3']
    zeros = ee.Image(ee.Array([ee.List.repeat(0, len(harmonicTag))])).arrayRepeat(0, nSegments)
    coefImg = fit.select(bandTag).arrayCat(zeros, 0).float().arraySlice(0, 0, nSegments)
    tags = [tag + '_' + targetBand + '_coef' for tag in segmentTag]
    coefImages = coefImg.arrayFlatten([tags, harmonicTag])
    return ee.Image.cat(coefImages, magImages, rmseImages)

def buildStartEndBreakProb(fit, nSegments, tag):
  # Build breakpoint information images from the CCDC result (tStart, tEnd, tBreak, changeProb)
    segmentTag = [f"S{i}_{tag}" for i in range(1, nSegments + 1)]
    zeros = ee.Array(0).repeat(0, nSegments)
    magImg = fit.select(tag).arrayCat(zeros, 0).float().arraySlice(0, 0, nSegments)
    return magImg.arrayFlatten([segmentTag])

def buildCcdImage(fit, nSegments):
    # tProb_filtered = tProb.updateMask(tProb.eq(1)) can be used to export only pixels with prob = 1
    tProb = buildStartEndBreakProb(fit, nSegments, 'changeProb')
    tStart = buildStartEndBreakProb(fit, nSegments, 'tStart')
    tEnd = buildStartEndBreakProb(fit, nSegments, 'tEnd')
    tBreak = buildStartEndBreakProb(fit, nSegments, 'tBreak')
    return ee.Image.cat(tStart, tEnd, tBreak, tProb);

