import ee

ee.Authenticate()
ee.Initialize(project="ee-yulinjiang68")

def prepare_l4l5l7_col2(image):
    band_list = ['SR_B1', 'SR_B2', 'SR_B3', 'SR_B4', 'SR_B5', 'SR_B7']
    sub_band = ['BLUE', 'GREEN', 'RED', 'NIR', 'SWIR1', 'SWIR2']

    optical_bands = image.select('SR_B.').multiply(0.0000275).add(-0.2)
    scaled = optical_bands.select(band_list).rename(sub_band)

    valid_qa = [5440, 5504]

    mask1 = image.select(['QA_PIXEL']).remap(valid_qa, [1] * len(valid_qa), 0)
    mask2 = image.select('QA_RADSAT').eq(0)
    mask3 = scaled.select(sub_band).reduce(ee.Reducer.min()).gt(0)
    mask4 = scaled.select(sub_band).reduce(ee.Reducer.max()).lt(1)
    mask5 = image.select("SR_ATMOS_OPACITY").unmask(-1).lt(300)

    return scaled.updateMask(mask1.And(mask2).And(mask3).And(mask4).And(mask5)).multiply(1e4).copyProperties(image, ['system:time_start'])

def prepare_l8_col2(image):
    band_list = ['SR_B2', 'SR_B3', 'SR_B4', 'SR_B5', 'SR_B6', 'SR_B7']
    sub_band = ['BLUE', 'GREEN', 'RED', 'NIR', 'SWIR1', 'SWIR2']

    optical_bands = image.select('SR_B.').multiply(0.0000275).add(-0.2)
    scaled = optical_bands.select(band_list).rename(sub_band)

    valid_toa = [2, 4, 32, 66, 68, 96, 100, 130, 132, 160, 164]
    valid_qa = [21824, 21888]

    mask1 = image.select(['QA_PIXEL']).remap(valid_qa, [1] * len(valid_qa), 0)
    mask2 = image.select('QA_RADSAT').eq(0)
    mask3 = scaled.select(sub_band).reduce(ee.Reducer.min()).gt(0)
    mask4 = scaled.select(sub_band).reduce(ee.Reducer.max()).lt(1)
    mask5 = image.select(['SR_QA_AEROSOL']).remap(valid_toa, [1] * len(valid_toa), 0)

    return scaled.updateMask(mask1.And(mask2).And(mask3).And(mask4).And(mask5)).multiply(1e4).copyProperties(image, ['system:time_start'])

def getLandsat(start, end, endl7, roi):
    collection8 = ee.ImageCollection('LANDSAT/LC08/C02/T1_L2').filterDate(start, end).map(prepare_l8_col2);
    collection7 = ee.ImageCollection('LANDSAT/LE07/C02/T1_L2').filterDate(start, endl7).map(prepare_l4l5l7_col2);
    collection5 = ee.ImageCollection('LANDSAT/LT05/C02/T1_L2').filterDate(start, end).map(prepare_l4l5l7_col2);
    collection4 = ee.ImageCollection('LANDSAT/LT04/C02/T1_L2').filterDate(start, end).map(prepare_l4l5l7_col2);
    col = collection4.merge(collection5).merge(collection7).merge(collection8).filterBounds(roi)
    return col

